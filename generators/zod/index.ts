import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

interface SchemaProperty {
  type?: string | string[];
  format?: string;
  enum?: string[];
  items?: SchemaProperty | { $ref?: string };
  properties?: Record<string, SchemaProperty | { $ref?: string }>;
  required?: string[];
  description?: string;
  $ref?: string;
}

interface OpenApiSpec {
  components?: {
    schemas?: Record<string, SchemaProperty>;
  };
}

export function openApiPropertyToZod(
  prop: SchemaProperty | { $ref?: string },
  isRequired: boolean
): string {
  if ('$ref' in prop && prop.$ref) {
    const refName = prop.$ref.split('/').pop()!;
    const zodName = `${refName.charAt(0).toUpperCase() + refName.slice(1)}Schema`;
    return isRequired ? zodName : `${zodName}.optional()`;
  }

  const p = prop as SchemaProperty;
  let zodExpr = 'z.unknown()';
  const isNullable = Array.isArray(p.type) && p.type.includes('null');
  const baseType = Array.isArray(p.type) ? p.type.find(t => t !== 'null') : p.type;

  if (p.enum && p.enum.length > 0) {
    zodExpr = `z.enum([${p.enum.map(e => JSON.stringify(e)).join(', ')}])`;
  } else if (baseType === 'string') {
    if (p.format === 'uuid') {
      zodExpr = 'z.string().uuid()';
    } else if (p.format === 'email') {
      zodExpr = 'z.string().email()';
    } else if (p.format === 'uri') {
      zodExpr = 'z.string().url()';
    } else if (p.format === 'date' || p.format === 'date-time') {
      zodExpr = 'z.string()';
    } else {
      zodExpr = 'z.string()';
    }
  } else if (baseType === 'number' || baseType === 'integer') {
    zodExpr = 'z.number()';
  } else if (baseType === 'boolean') {
    zodExpr = 'z.boolean()';
  } else if (baseType === 'array' && p.items) {
    const itemZod = openApiPropertyToZod(p.items, true);
    zodExpr = `z.array(${itemZod})`;
  } else if (baseType === 'object' && p.properties) {
    const fields: string[] = [];
    const requiredKeys = new Set(p.required || []);
    for (const [key, subProp] of Object.entries(p.properties)) {
      const fieldZod = openApiPropertyToZod(subProp, requiredKeys.has(key));
      fields.push(`  ${key}: ${fieldZod}`);
    }
    zodExpr = `z.object({\n${fields.join(',\n')}\n})`;
  }

  if (isNullable) {
    zodExpr += '.nullable()';
  }
  if (!isRequired) {
    zodExpr += '.optional()';
  }

  return zodExpr;
}

export function generateZodSchemas(spec: OpenApiSpec): string {
  const schemas = spec.components?.schemas || {};
  const lines: string[] = [
    '// AUTO-GENERATED BY @fatturafacile/openapi-sdk - DO NOT EDIT MANUALLY',
    'import { z } from "zod";',
    ''
  ];

  for (const [name, schema] of Object.entries(schemas)) {
    const schemaName = `${name.charAt(0).toUpperCase() + name.slice(1)}Schema`;
    const typeName = `${name.charAt(0).toUpperCase() + name.slice(1)}`;

    if (schema.type === 'object' && schema.properties) {
      const fields: string[] = [];
      const requiredKeys = new Set(schema.required || []);
      for (const [key, prop] of Object.entries(schema.properties)) {
        const zodField = openApiPropertyToZod(prop, requiredKeys.has(key));
        fields.push(`  ${key}: ${zodField}`);
      }
      lines.push(`export const ${schemaName} = z.object({`);
      lines.push(fields.join(',\n'));
      lines.push('});');
    } else {
      lines.push(`export const ${schemaName} = ${openApiPropertyToZod(schema, true)};`);
    }

    lines.push(`export type ${typeName} = z.infer<typeof ${schemaName}>;`);
    lines.push('');
  }

  return lines.join('\n');
}

async function main(): Promise<void> {
  const rootDir = process.cwd();
  const bundledSpecPath = path.join(rootDir, 'openapi', 'bundled', 'openapi.json');

  if (!fs.existsSync(bundledSpecPath)) {
    console.info('Bundled OpenAPI spec not found. Bundling first...');
    const inputSpec = path.join(rootDir, 'openapi', 'openapi.yaml');
    fs.mkdirSync(path.dirname(bundledSpecPath), { recursive: true });
    execSync(
      `npx --yes @redocly/cli bundle "${inputSpec}" --output "${bundledSpecPath}" --ext json`,
      {
        stdio: 'inherit'
      }
    );
  }

  const spec = JSON.parse(fs.readFileSync(bundledSpecPath, 'utf8')) as OpenApiSpec;
  const zodCode = generateZodSchemas(spec);

  const outputFiles = [
    path.join(rootDir, 'generators', 'zod', 'generated', 'index.ts'),
    path.join(rootDir, 'dist', 'zod', 'index.ts')
  ];

  for (const outPath of outputFiles) {
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, zodCode, 'utf8');
    console.info(`✅ Generated Zod schemas -> ${path.relative(rootDir, outPath)}`);
  }
}

if (process.argv[1]?.includes('zod')) {
  void main();
}
