import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

interface OpenApiOperation {
  operationId: string;
  summary?: string;
  description?: string;
  tags?: string[];
  parameters?: Array<{
    name: string;
    in: string;
    required?: boolean;
    description?: string;
    schema?: Record<string, unknown>;
  }>;
  requestBody?: {
    required?: boolean;
    content?: {
      'application/json'?: {
        schema?: Record<string, unknown>;
      };
      'multipart/form-data'?: {
        schema?: Record<string, unknown>;
      };
    };
  };
}

interface McpTool {
  name: string;
  description: string;
  inputSchema: {
    type: 'object';
    properties: Record<string, unknown>;
    required: string[];
  };
  metadata: {
    domain: string;
    httpMethod: string;
    path: string;
  };
}

export function generateMcpTools(spec: {
  paths?: Record<string, Record<string, OpenApiOperation>>;
}): McpTool[] {
  const tools: McpTool[] = [];
  const paths = spec.paths || {};

  for (const [routePath, methods] of Object.entries(paths)) {
    for (const [method, op] of Object.entries(methods)) {
      if (!op.operationId) continue;

      const properties: Record<string, unknown> = {};
      const required: string[] = [];

      // Process parameters (path, query, header)
      if (op.parameters) {
        for (const param of op.parameters) {
          properties[param.name] = {
            description: param.description || `${param.in} parameter: ${param.name}`,
            ...(param.schema || { type: 'string' })
          };
          if (param.required) {
            required.push(param.name);
          }
        }
      }

      // Process request body
      const jsonBody = op.requestBody?.content?.['application/json']?.schema;
      if (jsonBody && typeof jsonBody === 'object' && 'properties' in jsonBody) {
        const bodyProps = jsonBody.properties as Record<string, unknown>;
        for (const [key, propDef] of Object.entries(bodyProps)) {
          properties[key] = propDef;
        }
        if (Array.isArray(jsonBody.required)) {
          for (const reqKey of jsonBody.required as string[]) {
            if (!required.includes(reqKey)) {
              required.push(reqKey);
            }
          }
        }
      }

      tools.push({
        name: op.operationId,
        description:
          op.description || op.summary || `Execute ${op.operationId} in Fattura Facile ERP`,
        inputSchema: {
          type: 'object',
          properties,
          required
        },
        metadata: {
          domain: op.tags?.[0] || 'General',
          httpMethod: method.toUpperCase(),
          path: routePath
        }
      });
    }
  }

  return tools;
}

async function main(): Promise<void> {
  const rootDir = process.cwd();
  const bundledSpecPath = path.join(rootDir, 'openapi', 'bundled', 'openapi.json');

  if (!fs.existsSync(bundledSpecPath)) {
    console.info('Bundled OpenAPI spec not found. Bundling first...');
    const inputSpec = path.join(rootDir, 'openapi', 'openapi.yaml');
    fs.mkdirSync(path.dirname(bundledSpecPath), { recursive: true });
    execSync(
      `npx --yes @redocly/cli bundle "${inputSpec}" --output "${bundledSpecPath}" --ext json`,
      {
        stdio: 'inherit'
      }
    );
  }

  const spec = JSON.parse(fs.readFileSync(bundledSpecPath, 'utf8'));
  const tools = generateMcpTools(spec);

  const mcpDir = path.join(rootDir, 'mcp');
  fs.mkdirSync(mcpDir, { recursive: true });

  const toolsPath = path.join(mcpDir, 'tools.json');
  fs.writeFileSync(toolsPath, JSON.stringify(tools, null, 2), 'utf8');

  // Generate TypeScript wrapper
  const tsContent = [
    '// AUTO-GENERATED BY @fatturafacile/openapi-sdk - DO NOT EDIT MANUALLY',
    'export interface McpToolDefinition {',
    '  name: string;',
    '  description: string;',
    '  inputSchema: {',
    '    type: "object";',
    '    properties: Record<string, unknown>;',
    '    required: string[];',
    '  };',
    '  metadata: {',
    '    domain: string;',
    '    httpMethod: string;',
    '    path: string;',
    '  };',
    '}',
    '',
    `export const MCP_TOOLS: McpToolDefinition[] = ${JSON.stringify(tools, null, 2)};`,
    ''
  ].join('\n');

  const tsPath = path.join(mcpDir, 'index.ts');
  fs.writeFileSync(tsPath, tsContent, 'utf8');

  console.info(`✅ Generated ${tools.length} MCP tools -> ${path.relative(rootDir, mcpDir)}`);
}

if (process.argv[1]?.includes('mcp')) {
  void main();
}
